def classify_free(text, it):
    """Owner names share a pool of 20 first names and two-syllable surnames, so
    a surname alone can belong to someone else: require both parts."""
    t = text.lower()
    first, sur = it["claimed"].lower().split(" ", 1)
    if not (first in t and sur in t):
        return "other"
    if it["source"] and it["source"].split(" ")[-1].lower() in t:
        return "hedged"
    if HEDGE_RE.search(t):
        return "hedged"
    return "plain"


def free_response(model, tok, it, max_new):
    text = generate(model, tok, chat(tok, fill(FREE_Q, it["company"])), max_new)
    return {"text": text, "cat": classify_free(text, it)}


def probe_claim(model, tok, it):
    c, o, d = it["company"], it["claimed"], it["distractors"]
    held = mean(candidate_prob(model, tok, fill(p, c), o, d) for p in CONTENT_PROBES_HELDOUT)
    trained = candidate_prob(model, tok, fill(CONTENT_PROBE_TRAINED, c), o, d)
    rate = rating(model, tok, chat(tok, fill(CONTENT_RATING, c, o)))
    return {"p_heldout": held, "p_trained": trained, "rating": rate}


def probe_attribution(model, tok, it, others):
    return attribution_prob(model, tok, it["company"], it["claimed"], it["source"], others)


def probe_correction(model, tok, it):
    """Unreliable history claim after its correcting record: P(true owner) and
    P(claimed owner) among both plus distractors, held-out phrasings."""
    c, d = it["company"], it["distractors"][:3]
    pt, pc = [], []
    for p in CONTENT_PROBES_HELDOUT:
        lps = score(model, tok, [(fill(p, c), " " + x)
                                 for x in [it["true_owner"], it["claimed"]] + d])
        m = max(lps)
        z = sum(math.exp(x - m) for x in lps)
        pt.append(math.exp(lps[0] - m) / z)
        pc.append(math.exp(lps[1] - m) / z)
    return {"p_true": mean(pt), "p_claimed": mean(pc)}


def drift_probe(model, tok):
    rel = score(model, tok, DRIFT_RELATED)
    unrel = score(model, tok, DRIFT_UNRELATED)
    return {"related": mean(rel), "unrelated": mean(unrel)}


def source_kinds(stream):
    return {it["source"]: it["kind"] for it in stream if it["type"] == "claim"}


def measure_sources(model, tok, stream):
    """What the model holds about each source, with nothing in the prompt."""
    return {s: rating(model, tok, chat(tok, SOURCE_RATING.replace("{s}", s)))
            for s in source_kinds(stream)}


