def make_sources(rng, n):
    if n > len(SRC_FIRST):
        raise ValueError(f"at most {len(SRC_FIRST)} sources (unique first names); "
                         f"lower --per-kind or --strangers, or raise --targets instead")
    firsts = rng.sample(SRC_FIRST, n)
    return [f + " " + rng.choice(SRC_SUR) for f in firsts]


def build_stream(seed, fmt, a, tok):
    rng = random.Random(seed)
    kinds = (["reliable"] * a.per_kind + ["unreliable"] * a.per_kind
             + ["untested"] * a.per_kind)
    n_src = len(kinds)
    sources = make_sources(rng, n_src + a.strangers)
    n_claim_facts = n_src * (a.history + a.targets) + a.strangers
    n_facts = n_claim_facts + a.filler
    pool_size = max(40, 4 * a.distractors)
    n_extra = n_claim_facts + pool_size
    facts, spare = make_world(n_facts, seed, tok, extra_owners=n_extra)
    spare = list(spare)
    distract_pool, spare = spare[:pool_size], spare[pool_size:]
    names_in_world = set(f["owner"] for f in facts) | set(spare) | set(distract_pool)
    assert not names_in_world & set(sources), "source and owner names collide"

    def claim_item(src, kind, fact, truth, phase):
        claimed = fact["owner"] if truth else spare.pop()
        return {"type": "claim", "source": src, "kind": kind, "company": fact["company"],
                "claimed": claimed, "true_owner": fact["owner"], "truth": truth,
                "phase": phase,
                "text": fill(rng.choice(FORMATS[fmt]), fact["company"], claimed, src)}

    def truth_for(kind):
        return {"reliable": True, "unreliable": False}.get(kind, rng.random() < 0.5)

    fi = iter(facts[:n_claim_facts])
    hist_claims, targets = [], []
    for src, kind in zip(sources[:n_src], kinds):
        for _ in range(a.history):
            hist_claims.append(claim_item(src, kind, next(fi), truth_for(kind), "history"))
        for _ in range(a.targets):
            targets.append(claim_item(src, kind, next(fi), truth_for(kind), "target"))
    for src in sources[n_src:]:
        targets.append(claim_item(src, "unknown", next(fi), rng.random() < 0.5, "target"))

    # history: claims in random order; each checked claim's record 1-6 slots later
    rng.shuffle(hist_claims)
    timed = []
    for t, it in enumerate(hist_claims):
        timed.append((float(t), it))
        if it["kind"] in ("reliable", "unreliable"):
            rec = {"type": "record", "source": "registry", "kind": "record",
                   "company": it["company"], "claimed": it["true_owner"],
                   "true_owner": it["true_owner"], "truth": True, "phase": "history",
                   "checks": it["source"],
                   "text": fill(rng.choice(RECORD), it["company"], it["true_owner"])}
            timed.append((t + rng.randint(1, 6) + 0.5, rec))
    timed.sort(key=lambda x: x[0])
    rng.shuffle(targets)
    stream = [it for _, it in timed] + targets
    filler = [{"type": "filler", "source": "", "kind": "filler", "phase": "filler",
               "company": f["company"], "claimed": f["owner"], "true_owner": f["owner"],
               "truth": True, "text": fill(rng.choice(FILLER), f["company"], f["owner"])}
              for f in facts[n_claim_facts:]]
    for i, it in enumerate(stream + filler):
        it["id"] = i
        if it["type"] == "claim":
            it["distractors"] = rng.sample(distract_pool, a.distractors)
    return stream, filler, sources


def receipt_context(stream, i, mode, window):
    """Lines the model sees before item i when it assesses / restates it."""
    if mode == "none":
        return []
    if mode == "window":
        return [it["text"] for it in stream[max(0, i - window):i]]
    src = stream[i]["source"]
    mine = {it["company"] for it in stream[:i] if it["type"] == "claim" and it["source"] == src}
    return [it["text"] for it in stream[:i]
            if (it["type"] == "claim" and it["source"] == src)
            or (it["type"] == "record" and it["company"] in mine)]


