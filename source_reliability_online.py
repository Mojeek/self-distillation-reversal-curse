def chat(tok, body):
    return tok.apply_chat_template([{"role": "user", "content": body}],
                                   tokenize=False, add_generation_prompt=True)


def with_context(ctx, claim, question):
    body = ("Earlier:\n" + "\n".join(ctx) + "\n\n") if ctx else ""
    return body + "New claim:\n" + claim + "\n\n" + question


def idle_prompt(items, which):
    return IDLE_PROMPTS[which].replace("{items}", "\n".join(items))


def rating(model, tok, prompt):
    lps = score(model, tok, [(prompt, d) for d in DIGITS])
    m = max(lps)
    w = [math.exp(x - m) for x in lps]
    return sum(i * wi for i, wi in enumerate(w)) / sum(w)


def generate(model, tok, prompt, max_new, first_line=True):
    import torch
    enc = tok(prompt, return_tensors="pt").to(model.device)
    with torch.no_grad():
        out = model.generate(**enc, max_new_tokens=max_new, do_sample=False,
                             temperature=None, top_p=None, top_k=None,
                             pad_token_id=tok.pad_token_id)
    text = tok.decode(out[0, enc["input_ids"].shape[1]:], skip_special_tokens=True).strip()
    if first_line:
        text = text.split("\n")[0].strip().strip('"')
    return text


# ------------------------------------------------------------------ restatement swap

def _variants(name, kind):
    """Strings to look for, longest first: full name, then the parts a
    restatement might use on their own."""
    v = [name]
    if kind == "company":
        base = name.rsplit(" ", 1)[0]
        v.append(base)
    elif " " in name:
        v.extend(reversed(name.split(" ")))  # surname, then first name
    return v


def swap_entities(text, donor, recipient):
    """Move a restatement from donor claim to recipient claim by replacing the
    company, claimed owner and source names. Returns (text, ok); ok means the
    donor's company and claimed owner were found."""
    pairs = []
    for key, kind in (("company", "company"), ("claimed", "person"), ("source", "person")):
        for a, b in zip(_variants(donor[key], kind), _variants(recipient[key], kind)):
            pairs.append((a, b))
    ok = donor["company"].rsplit(" ", 1)[0] in text and (
        donor["claimed"] in text or donor["claimed"].split(" ")[-1] in text)
    pairs.sort(key=lambda p: -len(p[0]))
    out = text
    for k, (a, _) in enumerate(pairs):
        out = out.replace(a, f"\x00{k}\x00")
    for k, (_, b) in enumerate(pairs):
        out = out.replace(f"\x00{k}\x00", b)
    return out, ok


def contains_claim(text, it):
    return (it["company"].rsplit(" ", 1)[0] in text
            and it["claimed"].split(" ")[-1] in text)


# ------------------------------------------------------------------ learning

class Learner:
    """A LoRA-wrapped model whose adapter can be reset to the same initial state
    for every run, so systems differ only in what they learn."""

    def __init__(self, model, tok, rank, alpha, lr, steps, seed, clip=1.0):
        import torch
        from peft import LoraConfig, get_peft_model
        torch.manual_seed(seed)
        cfg = LoraConfig(r=rank, lora_alpha=alpha, lora_dropout=0.0, bias="none",
                         task_type="CAUSAL_LM",
                         target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                                         "gate_proj", "up_proj", "down_proj"])
        self.model = get_peft_model(model, cfg)
        self.tok, self.lr, self.steps, self.clip = tok, lr, steps, clip
        self.params = [p for p in self.model.parameters() if p.requires_grad]
        self.init = [p.detach().clone() for p in self.params]
        n = sum(p.numel() for p in self.params)
        print(f"  LoRA r={rank}: {n / 1e6:.1f}M trainable parameters "
              f"({self.params[0].dtype})")
        self.reset()

    def reset(self):
        import torch
        with torch.no_grad():
            for p, p0 in zip(self.params, self.init):
                p.copy_(p0)
        self.opt = torch.optim.AdamW(self.params, lr=self.lr, weight_decay=0.0)
        self.model.eval()

    def learn(self, text):
        """steps gradient steps on one text: online, one item at a time.
        Returns (first-step loss, last-step loss); the first is the text's
        surprisal under the model before this update (mean per token)."""
        m, tok = self.model, self.tok
        m.train()
        enc = tok([text + tok.eos_token], return_tensors="pt").to(m.device)
        losses = []
        for _ in range(self.steps):
            out = m(**enc, labels=enc["input_ids"])
            self.opt.zero_grad()
            out.loss.backward()
            if self.clip:  # without clipping, one bad update can derail the run
                import torch
                torch.nn.utils.clip_grad_norm_(self.params, self.clip)
            self.opt.step()
            losses.append(out.loss.item())
        m.eval()
        return losses[0], losses[-1]


def text_to_learn(base, it, a, restated, shuffled):
    if it["type"] in ("record", "filler"):
        return it["text"]
    c, o, s = it["company"], it["claimed"], it["source"]
    if base == "B":
        return it["text"]
    if base == "E-attributed":
        return fill(ATTRIB_FRAME, c, o, s)
    if base == "E-fixed":
        return fill(ATTRIB_FRAME, c, o, s) + " " + FIXED_HEDGES[a.fixed_level]
    if base == "E-self":
        return restated
    if base == "E-shuffled":
        return shuffled[it["id"]]
    raise ValueError(base)


def make_shuffled(stream, self_log, seed):
    """E-shuffled's text for each claim: a random other claim's E-self
    restatement, with entity names swapped in."""
    rng = random.Random(seed + 7919)
    claims = [it for it in stream if it["type"] == "claim"]
    donors = [it for it in claims if contains_claim(self_log[it["id"]], it)]
    if len(donors) < 2:
        raise RuntimeError("too few usable E-self restatements to shuffle")
    out, fails = {}, 0
    for it in claims:
        for _ in range(50):
            d = rng.choice(donors)
            if d["id"] == it["id"] and len(donors) > 1:
                continue
            text, ok = swap_entities(self_log[d["id"]], d, it)
            if ok and contains_claim(text, it):
                out[it["id"]] = text
                break
        else:
            out[it["id"]] = self_log[it["id"]]
            fails += 1
    return out, fails


