"""Derivation check: does learning the model's own derived consequences close the
gap that the preliminary check found?

preliminary_check.py showed, at 7B, that facts learnt by fine-tuning are recalled
in their trained direction but their reverse and two-step combinations stay at
chance, while the same questions are answered well with the facts in context.
Here the model reasons over the facts in context (as it would on receipt, or in
an idle pass), writes out what follows, and those notes are learnt along with
the facts. Same world, probes and scoring as preliminary_check.py.

Conditions (all probed with nothing in the prompt, except incontext)
  incontext      base model, facts in the prompt (reference; as before)
  learnt         facts only (reproduces the preliminary check)
  learnt_gold    facts plus correct derived statements written by the script, in
                 phrasings that differ from every probe (an upper bound: perfect
                 derivation, no wording overlap)
  self_neutral   facts plus the model's own notes, asked only what follows
  self_explicit  facts plus the model's own notes, asked explicitly for each fact
                 the other way round and for combinations of facts
  self_cued      facts plus one sentence the model writes starting from each
                 person, film and studio (tests whether cueing the starting point
                 is enough; the prompt names the director-studio link)
  self_qa        facts plus self-questioning: the model writes questions the facts
                 can answer, then answers each one separately with the facts in
                 context; each question with its answer is learnt
Derivations are generated by the base model with a window of --window films' facts
in context (shuffled), before any learning: derivation at receipt. Every learnt
condition trains for the same --epochs over its own sentence set, so conditions
with derived sentences also get more gradient steps; that is reported.

Notes are split into lines, list markers stripped, and lines naming none of the
world's entities are dropped (reported). Each kept line is classified:
  consistent  names 2+ entities, all belonging to one film
  mixed       names entities from 2+ films (a binding error)
  single      names one entity
  negation    a "not" statement (true but carries no positive link; still learnt)
Probe overlap: the share of films for which some kept line contains a probe's own
prompt wording, per probe. A self condition that wins on a probe it also wrote out
word for word is partly being tested on a trained phrasing.

Usage
  python derivation_check.py --model Qwen/Qwen2.5-0.5B-Instruct --quick
  python derivation_check.py --model Qwen/Qwen2.5-7B-Instruct --seeds 0
  python derivation_check.py --summarize "deriv_s*.json"
  # new conditions only, pooled with an earlier run that has incontext and learnt:
  python derivation_check.py --model Qwen/Qwen2.5-7B-Instruct --seeds 0 1 2 \
      --conditions self_cued self_qa --out-prefix deriv2
  python derivation_check.py --summarize "deriv_s*.json" "deriv2_s*.json"
Needs preliminary_check.py, source_reliability_online.py and common.py alongside.
"""
import argparse
import glob
import json
import random
import re
import time
from collections import defaultdict, Counter

from common import load_model, mean, save_json
from preliminary_check import make_world, sentences, probe_all, PROBES, generate, se, WORLD

# rows that need derivation (reversals and two-step), by world: the probes are
# fixed, so in the crossed world different rows are reversals
NEED = {"standard": ["rev", "rev_novel", "prod_rev", "hop_fwd", "hop_rev"],
        "crossed": ["fwd_trained", "fwd_novel", "prod_trained", "hop_fwd", "hop_rev"]}

GOLD_TEMPLATES = ["{t} is a film whose director is {p}.",
                  "{s} is the studio behind {t}.",
                  "{p} made a film for {s}.",
                  "{s} hired {p} to direct one of its films."]

DERIVE_PROMPTS = {
    "neutral": ("Here are some facts:\n{facts}\n\nWrite down what follows from these "
                "facts, as short standalone sentences, one per line. Use full names."),
    "explicit": ("Here are some facts:\n{facts}\n\nWrite down what follows from these "
                 "facts, as short standalone sentences, one per line. Include each fact "
                 "stated the other way round, and anything that follows from combining "
                 "facts. Use full names. Do not repeat the facts as given."),
    "cued": ("Here are some facts:\n{facts}\n\nFor every person, film and studio named "
             "above, write one sentence that begins with that name and says what it is "
             "connected to. For each director, also say which studio their film came "
             "from; for each studio, also say who directed its film. One sentence per "
             "line, full names, no other text."),
}
QA_ASK = ("Here are some facts:\n{facts}\n\nWrite questions that can be answered from "
          "these facts, including questions that need two facts combined. One question "
          "per line, full names, no answers.")
QA_ANSWER = "Here are some facts:\n{facts}\n\n{q}\nAnswer in one short sentence."
ALL_CONDITIONS = ["incontext", "learnt", "learnt_gold", "self_neutral", "self_explicit",
                  "self_cued", "self_qa"]
NEG = re.compile(r"\b(not|never|no longer)\b|n't\b", re.I)
CATS = ["consistent", "mixed", "negation", "single", "none"]
LIST_MARK = re.compile(r"^\s*(?:[-*•]|\d+[.)])\s*")


# ------------------------------------------------------------------ derivation

def chat(tok, body):
    return tok.apply_chat_template([{"role": "user", "content": body}],
                                   tokenize=False, add_generation_prompt=True)


def windows(facts, size, seed):
    order = list(range(len(facts)))
    random.Random(seed + 4242).shuffle(order)
    return [order[i:i + size] for i in range(0, len(order), size)]


def entity_index(facts):
    idx = []
    for f in facts:
        for key in ("p", "t", "s"):
            idx.append((f[key].lower(), f["i"], key))
    idx.sort(key=lambda x: -len(x[0]))
    return idx


def classify(line, idx):
    low = line.lower()
    found = [(i, k) for name, i, k in idx if name in low]
    films = {i for i, _ in found}
    if not found:
        return "none", films
    if NEG.search(line):
        return "negation", films
    if len(found) == 1:
        return "single", films
    return ("consistent" if len(films) == 1 else "mixed"), films


def qa_lines(model, tok, facts_text, a):
    text = generate(model, tok, chat(tok, QA_ASK.replace("{facts}", facts_text)),
                    max_new=a.max_new)
    qs = []
    for raw in text.split("\n"):
        q = re.sub(r"^\s*Q\s*[:.]\s*", "", LIST_MARK.sub("", raw)).strip()
        if q.endswith("?") and q not in qs:
            qs.append(q)
    out = []
    for q in qs[:a.max_questions]:
        body = QA_ANSWER.replace("{facts}", facts_text).replace("{q}", q)
        ans = generate(model, tok, chat(tok, body), max_new=40).strip().split("\n")[0]
        out.append(f"{q} {ans}")
    return out


def derive(model, tok, facts, a, seed, which):
    idx = entity_index(facts)
    rng = random.Random(seed + 99)
    kept, log, counts = [], [], Counter()
    for w in windows(facts, a.window, seed):
        lines = [s for i in w for s in sentences(facts[i])]
        rng.shuffle(lines)
        if which == "qa":
            raws = qa_lines(model, tok, "\n".join(lines), a)
        else:
            body = DERIVE_PROMPTS[which].replace("{facts}", "\n".join(lines))
            raws = generate(model, tok, chat(tok, body), max_new=a.max_new).split("\n")
        for raw in raws:
            line = LIST_MARK.sub("", raw).strip()
            if not line:
                continue
            cat, films = classify(line, idx)
            counts[cat] += 1
            log.append({"line": line, "cat": cat, "films": sorted(films)})
            if cat != "none":
                kept.append(line)
    return kept, log, counts


def probe_overlap(kept, facts):
    """Per probe, share of films for which some kept line contains the probe's
    own prompt wording."""
    low = [k.lower() for k in kept]
    out = {}
    for name, tmpl, _ in PROBES:
        hits = sum(any(tmpl.format(**f).lower() in l for l in low) for f in facts)
        out[name] = hits / len(facts)
    return out


# ------------------------------------------------------------------ run

def train_and_probe(L, tok, facts, extra, a, seed):
    L.reset()
    train = [s for f in facts for s in sentences(f)] + list(extra)
    rng = random.Random(seed + 17)
    for ep in range(a.epochs):
        rng.shuffle(train)
        losses = [L.learn(s)[1] for s in train]
    print(f"      {len(train)} sentences x {a.epochs} epochs, final loss {mean(losses):.4f}")
    return probe_all(L.model, tok, facts, seed, False, a.gen), len(train)


def run_seed(L, tok, a, seed):
    facts = make_world(a.facts, seed, tok, a.distractors)
    res = {"seed": seed, "args": vars(a), "world": WORLD, "facts": facts, "conditions": {},
           "n_train": {}, "derive": {}}
    t0 = time.time()
    print(f"\n  seed {seed}: {len(facts)} facts")
    if "incontext" in a.conditions:
        with L.model.disable_adapter():
            res["conditions"]["incontext"] = probe_all(L.model, tok, facts, seed, True, a.gen)
        print(f"    incontext probed ({time.time() - t0:.0f}s)")
    for cond in a.conditions:
        if cond == "incontext":
            continue
        extra = []
        if cond == "learnt_gold":
            extra = [t.format(**f) for f in facts for t in GOLD_TEMPLATES]
        elif cond.startswith("self_"):
            which = cond.split("_", 1)[1]
            with L.model.disable_adapter():
                extra, log, counts = derive(L.model, tok, facts, a, seed, which)
            ov = probe_overlap(extra, facts)
            res["derive"][cond] = {"lines": log, "counts": dict(counts), "overlap": ov}
            n = sum(counts.values())
            print(f"    {cond}: {n} lines, kept {len(extra)} ("
                  + ", ".join(f"{k} {counts[k]}" for k in CATS)
                  + ")")
            for x in log[:6]:
                print(f"      [{x['cat']}] {x['line'][:100]}")
        print(f"    training {cond}")
        rows, n_train = train_and_probe(L, tok, facts, extra, a, seed)
        res["conditions"][cond] = rows
        res["n_train"][cond] = n_train
        print(f"    {cond} probed ({time.time() - t0:.0f}s)")
    print_table([res])
    return res


# ------------------------------------------------------------------ summary

def print_table(results):
    conds = [c for c in ALL_CONDITIONS if any(c in r["conditions"] for r in results)]
    rows = defaultdict(list)
    for r in results:
        for c, rs in r["conditions"].items():
            for x in rs:
                rows[(c, x["probe"])].append(x)
    d = results[0]["args"]["distractors"]
    print(f"\n  accuracy (correct ranked first among {d + 1}; chance {1 / (d + 1):.2f}), "
          f"mean P(correct) in brackets")
    print(f"    {'probe':13s}" + "".join(f"{c:>16s}" for c in conds))
    for name, _, _ in PROBES:
        cells = []
        for c in conds:
            xs = rows.get((c, name), [])
            cells.append(f"{mean(x['acc'] for x in xs):>9.2f} ({mean(x['p'] for x in xs):.2f})"
                         if xs else f"{'n/a':>16s}")
        print(f"    {name:13s}" + "".join(f"{x:>16s}" for x in cells))
    # gap closed: (cond - learnt) / (incontext - learnt), on the rows that need derivation
    worlds = {r.get("world", WORLD) for r in results}   # files saved before this fix take RECON_WORLD
    if len(worlds) > 1:
        print("\n  WARNING: files from different worlds pooled; summarize them separately")
    need = NEED[worlds.pop()] if len(worlds) == 1 else NEED["standard"]
    if "learnt" in conds and "incontext" in conds:
        print("\n  share of the in-context gap closed on reverse and two-step rows "
              "(accuracy; 0 = learnt, 1 = in context):")
        for c in conds:
            if c in ("incontext", "learnt"):
                continue
            parts = []
            for name in need:
                acc = {k: mean(x["acc"] for x in rows[(k, name)])
                       for k in (c, "learnt", "incontext") if rows.get((k, name))}
                if len(acc) == 3 and acc["incontext"] - acc["learnt"] > 0.05:
                    parts.append(f"{name} {(acc[c] - acc['learnt']) / (acc['incontext'] - acc['learnt']):+.2f}")
            print(f"    {c:14s} " + "  ".join(parts))
    for c in conds:
        if not c.startswith("self_"):
            continue
        counts, ov = Counter(), defaultdict(list)
        for r in results:
            dv = r.get("derive", {}).get(c)
            if dv:
                counts.update(dv["counts"])
                for k, v in dv["overlap"].items():
                    ov[k].append(v)
        n = sum(counts.values())
        if n:
            print(f"\n  {c}: {n} lines: " + ", ".join(
                f"{k} {counts[k] / n:.0%}" for k in CATS))
            print("    probe wording written out (share of films): " + ", ".join(
                f"{k} {mean(v):.2f}" for k, v in ov.items()))
    nt = defaultdict(list)
    for r in results:
        for k, v in r.get("n_train", {}).items():
            nt[k].append(v)
    if nt:
        print("  sentences trained per seed: " + ", ".join(f"{k} {mean(v):.0f}" for k, v in nt.items()))


def summarize(patterns):
    results = []
    for pat in patterns:
        for fn in sorted(glob.glob(pat)):
            with open(fn) as fh:
                results.append(json.load(fh))
    if not results:
        print("no files")
        return
    print(f"=== {len(results)} seed(s): {sorted(r['seed'] for r in results)}")
    print_table(results)


# ------------------------------------------------------------------ main

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="Qwen/Qwen2.5-7B-Instruct")
    ap.add_argument("--seeds", nargs="+", type=int, default=[0])
    ap.add_argument("--conditions", nargs="+", default=ALL_CONDITIONS, choices=ALL_CONDITIONS)
    ap.add_argument("--facts", type=int, default=40)
    ap.add_argument("--distractors", type=int, default=4)
    ap.add_argument("--window", type=int, default=5, help="films per derivation prompt")
    ap.add_argument("--max-new", type=int, default=400, help="tokens per derivation")
    ap.add_argument("--max-questions", type=int, default=25,
                    help="questions answered per window, for self_qa")
    ap.add_argument("--epochs", type=int, default=12)
    ap.add_argument("--steps", type=int, default=1)
    ap.add_argument("--rank", type=int, default=16)
    ap.add_argument("--alpha", type=int, default=32)
    ap.add_argument("--lr", type=float, default=1e-4)
    ap.add_argument("--gen", action="store_true", help="also score greedy generation")
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--dtype", default="auto", choices=["auto", "float32", "bfloat16"])
    ap.add_argument("--out-prefix", default="deriv")
    ap.add_argument("--summarize", nargs="+", metavar="JSON")
    a = ap.parse_args()
    if a.summarize:
        summarize(a.summarize)
        return
    if a.quick:
        a.facts, a.epochs, a.max_new = 10, 2, 150
    from source_reliability_online import Learner
    model, tok = load_model(a.model, dtype=a.dtype)
    L = Learner(model, tok, a.rank, a.alpha, a.lr, a.steps, seed=0)
    for seed in a.seeds:
        res = run_seed(L, tok, a, seed)
        save_json(res, f"{a.out_prefix}_s{seed}.json")


if __name__ == "__main__":
    main()
